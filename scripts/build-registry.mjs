#!/usr/bin/env node
/**
 * Generates:
 *  - src/registry.js           lazy map ID -> () => import(module) for modules on disk
 *  - gallery/catalog-index.json serializable search index for ALL 2,000 IDs
 *    (title, category, motif, treatment, production status) without source.
 *  - <id>.meta.json            written from each module's exported metadata
 *
 * Only modules that exist on disk are registered. Planned IDs stay pending.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = fs.readFileSync(path.join(root, 'briefs/catalog.jsonl'), 'utf8').trim().split('\n').map(l => JSON.parse(l));
const progress = JSON.parse(fs.readFileSync(path.join(root, 'production/progress.json'), 'utf8'));

const present = catalog.filter(e => fs.existsSync(path.join(root, e.output.module)));
const lines = [
  '// GENERATED by scripts/build-registry.mjs — do not edit by hand.',
  '// Lazy registry: importing this file loads no animation source.',
  'export const registry = {',
  ...present.map(e => `  '${e.id}': () => import('./${path.relative(path.join(root, 'src'), path.join(root, e.output.module)).split(path.sep).join('/')}'),`),
  '};',
  '',
  '/** @param {string} id */',
  'export async function load(id) {',
  '  const loader = registry[id];',
  "  if (!loader) throw new Error(`Animation ${id} is not implemented in this library build`);",
  '  const mod = await loader();',
  '  return mod.default;',
  '}',
  '',
  'export const implementedIds = Object.keys(registry);',
  '',
];
fs.writeFileSync(path.join(root, 'src/registry.js'), lines.join('\n'));

const metaErrors = [];
const metaById = new Map();
for (const e of present) {
  try {
    const mod = await import(pathToFileURL(path.join(root, e.output.module)).href + `?v=${Date.now()}`);
    const def = mod.default;
    if (def.id !== e.id) throw new Error(`module id ${def.id} != ${e.id}`);
    metaById.set(e.id, def.metadata);
    fs.writeFileSync(path.join(root, e.output.metadata), JSON.stringify({...def.metadata, version: def.version, paramsSchema: def.paramsSchema, defaultParams: def.defaultParams}, null, 2) + '\n');
  } catch (err) {
    metaErrors.push(`${e.id}: ${err.message}`);
  }
}

const index = catalog.map(e => {
  const p = progress.entries[e.id] || {status: 'planned'};
  return {
    id: e.id, slug: e.slug, title: e.title, category: e.category, categoryName: e.categoryName,
    motif: e.motif, motifIndex: e.motifIndex, treatment: e.treatment, family: e.family,
    action: e.concreteAction, comparison: e.comparison, objects: e.objects,
    status: p.status, legalStatus: p.legalStatus, implemented: fs.existsSync(path.join(root, e.output.module)),
    titleEn: metaById.get(e.id) ? metaById.get(e.id).title : null,
    tags: metaById.get(e.id) ? metaById.get(e.id).tags : [],
    hasPresets: fs.existsSync(path.join(root, e.output.presets)),
    module: e.output.module, presets: e.output.presets, thumb: `production/evidence/${e.id}/thumb.png`,
    hasThumb: fs.existsSync(path.join(root, `production/evidence/${e.id}/thumb.png`)),
  };
});
fs.mkdirSync(path.join(root, 'gallery'), {recursive: true});
fs.writeFileSync(path.join(root, 'gallery/catalog-index.json'), JSON.stringify(index));
console.log(JSON.stringify({registered: present.length, indexEntries: index.length, metaErrors}, null, 2));
if (metaErrors.length) process.exitCode = 1;
